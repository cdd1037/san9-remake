    internal static string Format(string source)
    {
        int index = 0;
        return Printf().Replace(source, match => match.Value == "%%" ? "%" :
            "{" + index++ + (match.Groups[1].Value.Length == 0 ? "" : "," + match.Groups[1].Value) + "}");
    }

